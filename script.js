const UPLOAD_URL = "";

const weddingDate = new Date("2026-12-19T00:00:00");
function updateCountdown(){
  const now = new Date();
  let diff = Math.max(0, weddingDate.getTime() - now.getTime());
  const day = 86400000, hour = 3600000, minute = 60000;
  const values = {
    days: Math.floor(diff/day),
    hours: Math.floor((diff%day)/hour),
    minutes: Math.floor((diff%hour)/minute),
    seconds: Math.floor((diff%minute)/1000)
  };
  Object.entries(values).forEach(([id,value]) => {
    const el = document.getElementById(id);
    if(el) el.textContent = String(value).padStart(id === "days" ? 3 : 2,"0");
  });
}
updateCountdown();
setInterval(updateCountdown,1000);

if (UPLOAD_URL.trim()) {
  const link = document.getElementById("upload-link");
  const hint = document.getElementById("upload-hint");
  const qrArea = document.getElementById("qr-area");
  link.href = UPLOAD_URL;
  link.target = "_blank";
  link.rel = "noopener";
  link.removeAttribute("aria-disabled");
  link.innerHTML = 'Open the photo album <span>↗</span>';
  hint.textContent = "Scan the QR code or tap the button to add your photos.";
  // QR image is generated by QR Server only after you provide the real destination URL.
  const img = document.createElement("img");
  img.alt = "QR code to upload photos";
  img.width = 150;
  img.height = 150;
  img.src = "https://api.qrserver.com/v1/create-qr-code/?size=150x150&data=" + encodeURIComponent(UPLOAD_URL);
  qrArea.replaceChildren(img);
}
